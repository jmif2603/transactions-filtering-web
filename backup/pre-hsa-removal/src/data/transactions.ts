import type { Person, CardInfo } from './people';

export interface Transaction {
  merchantName: string;
  benefitAccount: string;
  transactionAmount: string;
  date: string;
  type: 'Cleared' | 'Pending';
  direction: 'MoneyIn' | 'MoneyOut';
  benefit: 'HSA_FSA' | 'DCFSA' | 'GHFSA' | 'RemoteWork';
  status?: 'ReceiptRequired' | 'Denied' | 'ApprovalPending' | 'InformationRequested' | 'AutoApproved' | 'Approved' | 'Paid' | 'PaymentPending';
  isCardSwipe?: boolean;
  claimStatus?: 'PENDING' | 'IN_REVIEW' | 'INFORMATION_REQUESTED' | 'RESUBMITTED' | 'APPROVED' | 'PAID' | 'IN_ACCRUAL' | 'REJECTED' | 'CANCELLED';
  orderSide?: 'BUY' | 'SELL';
  orderStatus?: 'FILLED' | 'PENDING' | 'PENDING_CANCEL' | 'CANCELED';
  transferSummary?: string;
  transferType?: 'ACH' | 'WIRE' | 'CHECK' | 'JOURNAL' | 'REINVESTMENT';
  transferExpectedDate?: string;
  /** Transaction Type filter group */
  kind: TransactionKind;
  /** Person the claim was filed for (Individual filter). Claims only. */
  claimantUid?: Person['uid'];
  /** Card that made the swipe (Card filter). Card transactions only. */
  cardId?: CardInfo['cardId'];
}

export type TransactionKind = 'CardTransaction' | 'ClaimReimbursement' | 'Contribution' | 'Deposit';

